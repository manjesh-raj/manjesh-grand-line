#!/usr/bin/env bash
# Prove every vendored web bundle was built from the inputs committed beside it.
#
#   Scripts/check-web-bundles.sh                     # check every Vendor/*/web
#   Scripts/check-web-bundles.sh --record Vendor/X Scripts/build-x-web.sh
#                                                    # print X's input digests
#
# R4-PROC-03 of the fourth full review. The app ships three web bundles
# (Excalidraw, Monaco, Schedule-X), each generated from `Vendor/<name>/src/`
# by its `Scripts/build-*-web.sh` and committed as `Vendor/<name>/web/`.
# Their `BUILD-INFO.txt` already records a SHA-256 of every *shipped* file,
# which the bundle's own suite asserts, so a hand edit to `web/` fails. What
# nothing caught was the other direction: an edit to `src/` (or to the build
# script) that was never rebuilt. The committed `web/` then silently ships the
# old behaviour, and the next person to touch `src/` cannot tell whether the
# bundle they are about to replace matches what they are reading.
#
# So each build script now also records a SHA-256 of every *input* - every
# file under `src/`, plus the build script itself - as `input sha256` lines in
# `BUILD-INFO.txt`, and this script recomputes them. It needs no node and no
# network, so it runs in `run-all-tests.sh`'s default and `--ci` selections
# (CI's blocking headless lane). The full rebuild-and-diff is still each build
# script's own `--check`, which needs npm and is run by hand.
#
# `--record` is the one definition of "a bundle's inputs": the build scripts
# call it to write those lines, so the list they write and the list this
# checks cannot disagree.
#
# Bundles are discovered by glob (`Vendor/*/web/BUILD-INFO.txt`), so a fourth
# one joins automatically - and fails until its build script records inputs.

set -euo pipefail
cd "$(dirname "$0")/.."

# The build script that generated a bundle, from BUILD-INFO.txt's first line
# ("Generated by native/Scripts/build-x-web.sh - ..."), relative to native/.
generator_of() {
  sed -n '1s|^Generated by native/\(Scripts/[^ ]*\.sh\).*|\1|p' "$1/web/BUILD-INFO.txt"
}

# Every input of the bundle at $1 (a `Vendor/<name>` directory) built by the
# script at $2: one `input sha256 <digest>  <path>` line each, sorted by path.
record() {
  local bundle="${1%/}" script="$2"
  if [ ! -d "$bundle/src" ]; then
    echo "check-web-bundles: $bundle has no src/ directory" >&2
    return 2
  fi
  if [ -z "$script" ] || [ ! -f "$script" ]; then
    echo "check-web-bundles: $bundle names no build script that exists ('$script')" >&2
    return 2
  fi
  { find "$bundle/src" -type f ! -name .DS_Store; echo "$script"; } | LC_ALL=C sort | while IFS= read -r f; do
    printf 'input sha256 %s  %s\n' "$(shasum -a 256 "$f" | cut -d' ' -f1)" "$f"
  done
}

if [ "${1:-}" = "--record" ]; then
  [ $# -eq 3 ] || { echo "usage: $0 --record Vendor/<name> Scripts/build-<name>-web.sh" >&2; exit 2; }
  record "$2" "$3"
  exit $?
fi
[ $# -eq 0 ] || { echo "unknown argument: $1 (see the header)" >&2; exit 2; }

checked=0
failed=0
for info in Vendor/*/web/BUILD-INFO.txt; do
  [ -f "$info" ] || continue
  bundle="${info%/web/BUILD-INFO.txt}"
  checked=$((checked + 1))
  recorded="$(grep '^input sha256 ' "$info" || true)"
  if [ -z "$recorded" ]; then
    echo "✗ $bundle: BUILD-INFO.txt records no input digests - rebuild it with $(generator_of "$bundle")"
    failed=$((failed + 1))
    continue
  fi
  if ! actual="$(record "$bundle" "$(generator_of "$bundle")")"; then
    failed=$((failed + 1))
    continue
  fi
  if [ "$recorded" = "$actual" ]; then
    echo "✓ $bundle/web was built from the committed inputs"
  else
    echo "✗ $bundle/web was NOT built from the committed inputs:"
    diff <(printf '%s\n' "$recorded") <(printf '%s\n' "$actual") | sed -n 's/^< /    recorded: /p; s/^> /    now:      /p'
    echo "  Run $(generator_of "$bundle") and commit the result."
    failed=$((failed + 1))
  fi
done

# A glob that matched nothing would otherwise read as a clean pass.
if [ "$checked" -eq 0 ]; then
  echo "check-web-bundles: found no Vendor/*/web/BUILD-INFO.txt - nothing was checked" >&2
  exit 1
fi
[ "$failed" -eq 0 ]
